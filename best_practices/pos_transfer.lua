-- ============================================================================
-- Модуль передачи/сохранения состояния позиции в текстовый файл
-- Файл: pos_transfer.lua
-- Назначение: Записывает переданную строку состояния позиции в файл.
-- Параметры: file_path (string) - путь к файлу, text (string) - строка с данными
-- ============================================================================

function pos_transfer(file_path, text)
    local f = io.open(file_path, "w")
    if f then
        f:write(text .. "\n")
        f:close()
    end
end